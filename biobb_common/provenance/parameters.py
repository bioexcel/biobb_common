"""Module containing the parsers of the simulation parameter files (GROMACS mdp, AMBER namelists)
recorded in the provenance of a building block execution."""
import re
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Optional, Union

from biobb_common.provenance import tracker
from biobb_common.tools import file_utils as fu

# Parameter values: numbers when the text is a number, otherwise the text without quotes
Value = Union[str, int, float]


@dataclass
class ParameterSet:
    """Parameters read from a file used by a building block execution."""
    # File name, ie: grompp.mdp
    name: str
    # Format of the file: "GROMACS mdp" or "AMBER namelist"
    file_format: str
    # True if the file was generated by the block (and removed after the execution), False for input files
    generated: bool
    values: dict[str, Value] = field(default_factory=dict)
    # Input file, None for generated files
    path: Optional[Path] = None
    # Generated again from the properties, because the execution was skipped by the restart property
    regenerated: bool = False


def parse_mdp(text: str) -> dict[str, Value]:
    """Return the parameters of a GROMACS mdp file: "key = value" lines, ";" comments.
    Repeated keys keep the last value, as grompp does."""
    values: dict[str, Value] = {}
    for line in text.splitlines():
        line = line.split(";", 1)[0]
        key, equal, value = line.partition("=")
        if equal and key.strip():
            values[key.strip()] = _value(value.strip())
    return values


def parse_namelist(text: str) -> dict[str, Value]:
    """Return the parameters of the Fortran namelists of an AMBER input file (mdin),
    ie: "&cntrl imin = 0, nstlim = 5000, /", as "cntrl.imin", "cntrl.nstlim".
    Repeated namelists are numbered: "wt[1].type", "wt[2].type". Lines outside
    the namelists (titles, restraint groups) and "!" comments are ignored."""
    tokens = _namelist_groups(text)
    counts: dict[str, int] = {}
    for name, _ in tokens:
        counts[name] = counts.get(name, 0) + 1
    values: dict[str, Value] = {}
    seen: dict[str, int] = {}
    for name, assignments in tokens:
        seen[name] = seen.get(name, 0) + 1
        prefix = f"{name}[{seen[name]}]" if counts[name] > 1 else name
        for key, value in assignments:
            values[f"{prefix}.{key}"] = value
    return values


# Parsers by file extension
PARSERS: dict[str, tuple[str, Callable[[str], dict[str, Value]]]] = {
    ".mdp": ("GROMACS mdp", parse_mdp),
    ".mdin": ("AMBER namelist", parse_namelist),
    ".in": ("AMBER namelist", parse_namelist),
}


def parse_file(path: Union[str, Path], generated: bool = False) -> Optional[ParameterSet]:
    """Return the parameters of a file with a known extension (mdp, mdin, in),
    None if the extension is unknown, the file can not be read or has no parameters
    (ie: tleap or cpptraj .in scripts, which are not namelists)."""
    path = Path(path)
    file_format, parser = PARSERS.get(path.suffix.lower(), (None, None))
    if not parser or not path.is_file():
        return None
    try:
        values = parser(path.read_text(errors="replace"))
    except OSError:
        return None
    if not values:
        return None
    return ParameterSet(name=path.name, file_format=file_format, generated=generated, values=values,
                        path=None if generated else path.resolve())


def capture_parameters(obj) -> None:
    """Read the parameter files generated by a building block before its temporary
    files are removed, ie: the grompp.mdp built by grompp from simulation_type, the
    input mdp and the mdp property. Called by BiobbObject.remove_tmp_files, only
    when provenance is enabled. Errors are logged and never stop the block."""
    if not tracker.is_enabled(obj):
        return
    try:
        obj._provenance_parameters = generated_parameters(obj)
    except Exception as error:
        fu.log(f"WARNING: Provenance parameters could not be read: {error}", obj.out_log, obj.global_log)


def generated_parameters(obj) -> list[ParameterSet]:
    """Return the parameters of the files generated by a block: output_*_path attributes
    that are not arguments of the block (ie: grompp output_mdp_path, sander output_mdin_path),
    found on the host or, if the attribute is a path inside the container, in the sandbox."""
    arguments = set(getattr(obj, "doc_arguments_dict", {})) | {a for io in ("in", "out") for a in obj.io_dict.get(io, {})}
    unique_dir = (getattr(obj, "stage_io_dict", None) or {}).get("unique_dir")
    parameter_sets: list[ParameterSet] = []
    paths: set[Path] = set()
    for attribute, value in vars(obj).items():
        if not (attribute.startswith("output_") and attribute.endswith("_path")) or attribute in arguments or not isinstance(value, (str, Path)):
            continue
        path = Path(value)
        if not path.is_file() and unique_dir:
            path = Path(unique_dir) / path.name
        if path.is_file() and path.resolve() not in paths:
            paths.add(path.resolve())
            parameter_set = parse_file(path, generated=True)
            if parameter_set:
                parameter_sets.append(parameter_set)
    return parameter_sets


def block_parameters(obj) -> list[ParameterSet]:
    """Return the parameters of a block execution: the ones of the generated parameter files
    (captured before they were removed, or read now if they still exist) or, if the block
    generated none, the ones of the input parameter files (ie: an mdp used as it is)."""
    parameter_sets = getattr(obj, "_provenance_parameters", None)
    if parameter_sets is None:
        parameter_sets = generated_parameters(obj)
    return parameter_sets or input_parameters(obj)


def restart_parameters(obj) -> list[ParameterSet]:
    """Return the parameters of an execution skipped by the restart property, whose parameter files
    were not generated: the ones of the files that the block writes again from its properties
    (BiobbObject.write_parameter_files, ie: the grompp.mdp of grompp) or, if it generates none, the
    ones of the input parameter files. Errors are logged and no parameters are returned."""
    try:
        with tempfile.TemporaryDirectory(prefix="biobb_parameters_") as directory:
            paths = obj.write_parameter_files(directory) if hasattr(obj, "write_parameter_files") else []
            parameter_sets = [parameter_set for parameter_set in (parse_file(path, generated=True) for path in paths or []) if parameter_set]
    except Exception as error:
        fu.log(f"WARNING: Provenance parameters of the skipped execution could not be generated: {error}", obj.out_log, obj.global_log)
        return []
    for parameter_set in parameter_sets:
        parameter_set.regenerated = True
    return parameter_sets or input_parameters(obj)


def input_parameters(obj) -> list[ParameterSet]:
    """Return the parameters of the input parameter files of a block (ie: an mdp used as it is)."""
    from biobb_common.provenance.record import file_paths
    inputs = (parse_file(path) for path in file_paths(obj, "in").values() if isinstance(path, (str, Path)) and path)
    return [parameter_set for parameter_set in inputs if parameter_set]


def _namelist_groups(text: str) -> list[tuple[str, list[tuple[str, Value]]]]:
    """Return the (name, [(key, value)]) of the namelists of a text, quotes are respected."""
    groups: list[tuple[str, list[tuple[str, Value]]]] = []
    # Comments are removed line by line, "!" inside quotes is kept
    text = "\n".join(_strip_comment(line) for line in text.splitlines())
    masked = _mask_quotes(text)
    for match in re.finditer(r"&(\w+)", masked):
        name = match.group(1).lower()
        if name == "end":
            continue
        start = match.end()
        end = start + len(_namelist_body(masked[start:]))
        # Keys (ie: "nstlim", "wt(1)") found in the text without quoted strings, each value runs until the next key
        keys = list(re.finditer(r"(\w+(?:\(\s*\d+\s*\))?)\s*=", masked[start:end]))
        assignments = []
        for index, key in enumerate(keys):
            value_end = keys[index + 1].start() if index + 1 < len(keys) else end - start
            value = text[start + key.end():start + value_end].strip().rstrip(",").strip()
            assignments.append((re.sub(r"\s+", "", key.group(1)).lower(), _value(value)))
        groups.append((name, assignments))
    return groups


def _mask_quotes(text: str) -> str:
    """Return the text with the characters inside quotes replaced by spaces, same length."""
    return re.sub(r"'[^']*'|\"[^\"]*\"", lambda match: match.group(0)[0] + " " * (len(match.group(0)) - 2) + match.group(0)[-1], text)


def _namelist_body(masked: str) -> str:
    """Return the text of a namelist (with masked quotes) until its end: "/", "&end" or the next namelist."""
    match = re.search(r"/|&", masked)
    return masked[:match.start()] if match else masked


def _strip_comment(line: str) -> str:
    quote = None
    for index, char in enumerate(line):
        if quote:
            quote = None if char == quote else quote
        elif char in "'\"":
            quote = char
        elif char == "!":
            return line[:index]
    return line


def _value(text: str) -> Value:
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
        return text[1:-1]
    if re.fullmatch(r"[+-]?\d+", text):
        return int(text)
    if re.fullmatch(r"[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?", text):
        return float(text)
    return text
